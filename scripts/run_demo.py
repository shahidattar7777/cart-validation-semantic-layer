"""Run each demo question twice: graph + semantic layer vs. flat-table SQL.

    python scripts/run_demo.py              # all questions, prints to console
    python scripts/run_demo.py q3           # one question
    python scripts/run_demo.py --md demo/RESULTS.md   # also write markdown
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from scripts.db import ROOT, connect  # noqa: E402

QDIR = ROOT / "demo" / "queries"


def title_of(sql: str) -> str:
    lines = [l[3:].strip() for l in sql.splitlines() if l.startswith("--")]
    out = []
    for l in lines:
        if not l:
            break
        out.append(l)
    return " ".join(out)


def run(cur, sql: str):
    cur.execute(sql)
    cols = [d.name for d in cur.description]
    return cols, cur.fetchall()


def fmt_table(cols, rows, width=60) -> str:
    def cell(v):
        s = "" if v is None else str(v)
        return s if len(s) <= width else s[: width - 3] + "..."
    data = [[cell(c) for c in cols]] + [[cell(v) for v in r] for r in rows]
    w = [max(len(r[i]) for r in data) for i in range(len(cols))]
    lines = [" | ".join(r[i].ljust(w[i]) for i in range(len(cols))) for r in data]
    lines.insert(1, "-+-".join("-" * x for x in w))
    if not rows:
        lines.append("(0 rows)")
    return "\n".join(lines)


def md_table(cols, rows) -> str:
    if not rows:
        return "_(0 rows)_"
    esc = lambda v: ("" if v is None else str(v)).replace("|", "\\|")  # noqa: E731
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(esc(v) for v in r) + " |" for r in rows]
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("only", nargs="?", help="e.g. q3")
    ap.add_argument("--md", help="write results to this markdown file")
    args = ap.parse_args()
    graph_files = sorted(QDIR.glob("q*.graph.sql"))
    if args.only:
        graph_files = [f for f in graph_files if f.name.startswith(args.only)]
    md = ["# Demo results", "", "Generated by `python scripts/run_demo.py --md demo/RESULTS.md`.", ""]
    with connect() as conn, conn.cursor() as cur:
        cur.execute("LOAD 'age'")
        cur.execute('SET search_path = ag_catalog, "$user", public')
        for gf in graph_files:
            nf = gf.with_name(gf.name.replace(".graph.sql", ".naive.sql"))
            gsql, nsql = gf.read_text(encoding="utf-8"), nf.read_text(encoding="utf-8")
            title = title_of(gsql)
            print("=" * 100 + f"\n{title}\n" + "=" * 100)
            gcols, grows = run(cur, gsql)
            print(f"\n[graph + semantic layer]  {len(grows)} rows\n" + fmt_table(gcols, grows))
            ncols, nrows = run(cur, nsql)
            print(f"\n[flat tables, no semantic layer]  {len(nrows)} rows\n" + fmt_table(ncols, nrows) + "\n")
            md += [f"## {title}", "", f"**Graph + semantic layer** (`{gf.name}`), {len(grows)} rows", "",
                   md_table(gcols, grows), "", f"**Flat tables, no semantic layer** (`{nf.name}`), {len(nrows)} rows",
                   "", md_table(ncols, nrows), ""]
    if args.md:
        Path(args.md).write_text("\n".join(md), encoding="utf-8")
        print(f"Wrote {args.md}")


if __name__ == "__main__":
    main()
